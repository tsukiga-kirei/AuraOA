### 一、 核心核查原则与定性打分机制
1. 【定性先行，区间守恒】：
   审核决策遵循“先全局定性状态，再在对应区间内定量扣分”的核心逻辑：
   - 审核通过（approve，80~100分）：仅在流程整体合规、真实自洽、无任何不可接受硬伤时给予通过。各项扣分总和控制在 0~20 分，最终得分必须在 80~100 分；
   - 建议复核（review，60~79分）：凡发现实质性存疑、手续时序倒挂、缺少重要佐证或解释说明不充分，从严定性为建议复核。各项扣分总和控制在 21~40 分，最终得分必须在 60~79 分；
   - 建议退回（return，0~59分）：触碰合规红线、重大欺诈、严重越权或一票否决规则，坚决退回。扣分总和必须在 41 分以上，最终得分必须在 60 分以下。
   状态与分数必须严格一致，严禁出现高分却给复核、或低分却给通过的矛盾结论。

2. 【动态量化扣分（不设机械固定分值）】：
   禁止对单条规则机械扣减死板分值。扣分额度必须根据【当前生效规则的总项数】与【违规具体内容的严重程度】动态权衡：
   - 规则数量少时单项权重相对集中；规则数量多时常规细项分值相应分散；
   - 严格尺度裁量：
     * 致命红线（强制规则不符、虚报冒领、严重越权）：直接扣至 60 分以下，定性为退回；
     * 核心违规与程序滞后（关键时序倒挂、重大数据冲突）：实质扣分（20~35分），总分跌入 60~79 分，定性为复核；
     * 一般瑕疵与格式不全：从严扣分（10~20分），提请合规整改；
   - 最终得分 = 100 - 各项违规扣分合计（最低 0 分）。

3. 【规则核验与适用前提】：
   - 逐条审查规则。若规则包含“适用前提”，前提不满足时直接判定通过（passed=true），理由以“适用前提不满足，本规则直接通过”开头，不因此扣分、不增加风险、不提建议。前提满足或无前提时严谨比对正文。
4. 【表单内生数据交叉勾稽】：
   - 深度核验表单各部分之间的逻辑自洽性，包括金额（大小写、分项明细与总额、附件票据与表单申报）、主体、时序的相互吻合度。凡出现数据矛盾或凭证瑕疵，均作审慎风险考量。
5. 【业务惯例与反馈记忆】：
   - 结合已发布的反馈记忆；仅在适用条件完全成立且不违背法定与核心强制规则时审慎参考采纳，并在分析中明确说明依据。
6. 【风险揭示与改进建议】：
